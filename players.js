function enqueuePlayerUpdate(data) {
  playerOutbox.push({player: activePlayer.id, data});
  storePlayerOutbox();
  flushPlayerUpdates();
}

function applyPendingAlbumUpdate(profile, data) {
  if (data.kind === 'sticker' && Object.hasOwn(profile.stickers, data.sticker)) {
    profile.stickers[data.sticker] = data.placed === false ? null : {
      ...profile.stickers[data.sticker],
      ...Object.fromEntries(['x','y','page','scale','rotation','boardX','boardY'].filter(key => data[key] !== undefined).map(key => [key,data[key]])),
    };
    if (data.boardReset === true && profile.stickers[data.sticker]) {
      delete profile.stickers[data.sticker].boardX;
      delete profile.stickers[data.sticker].boardY;
    }
  } else if (data.kind === 'album-page') {
    profile.albumPages = Math.max(profile.albumPages || 1, data.pages);
    profile.albumPage = data.page;
  } else if (data.kind === 'album-view') {
    profile.albumView = {...profile.albumView,x:data.x,y:data.y,...(data.zoom!==undefined?{zoom:data.zoom}:{})};
  }
}

async function flushPlayerUpdates() {
  if (writingPlayer) return;
  writingPlayer = true;
  try {
    while (activePlayer) {
      const index = playerOutbox.findIndex(item => item.player === activePlayer.id);
      if (index < 0) break;
      const {player, data} = playerOutbox[index];
      const result = await playerRequest('/' + player, data);
      playerOutbox.splice(index, 1);
      storePlayerOutbox();
      if (activePlayer?.id === player) {
        // Preserve any newer preference changes still waiting to be saved.
        result.preferences = activePlayer.preferences;
        // An earlier response must not undo a newer move waiting in the outbox.
        for (const item of playerOutbox) {
          if (item.player === player) applyPendingAlbumUpdate(result, item.data);
        }
        const previous = Object.keys(activePlayer.stickers);
        activePlayer = result;
        if (data.kind === 'round') window.bunnyMario?.refreshAccess();
        if (phase === 'player-album' && !albumDrag && !['preference', 'sticker', 'album-page', 'album-view'].includes(data.kind)) {
          renderPlayerAlbum();
          if(data.kind==='album-decoration')message(result.albumDecoration===data.decoration?'Оформление выбрано.':'Пока не хватает монет на оформление.');
          if(data.kind==='redeem')message('Персонажи выдаются за достижения. Монеты можно потратить на оформление.');
        }
        if (phase === 'finished' && data.kind === 'round') {
          const unlocked = Object.keys(result.stickers).filter(key => !previous.includes(key));
          $('round-album').textContent = unlocked.length ? '✨ Новая наклейка! Открыть альбом' : '📒 Мой альбом';
          if(game==='mission'&&result.lastMission?.id===data.id){
            const outcome=result.lastMission;
            $('heading').textContent=outcome.awarded?'🏆 Наклейка получена!':outcome.passed?'Этап выполнен!':'Попробуй ещё раз';
            message('Верно сразу: '+score+' · Исправлено: '+rewardRound.corrected+'\n'+
              (outcome.awarded?'Наклейка уже в альбоме.':outcome.passed?'Сохранено этапов: '+outcome.completed+'/'+outcome.stages+'. Следующая миссия — по другой теме.':
              'Для награды нужно '+outcome.required+' верных. Выполненные этапы сохранены.'));
          }
        }
      }
    }
  } catch (error) {
    if (error.status === 401) return;
    if (phase === 'player-album' || phase === 'player-select') {
      message('Сервер недоступен. Изменения ожидают отправки.');
    } else if (phase === 'finished' && activePlayer) {
      $('round-album').textContent = '📒 Альбом · сохранение ожидается';
    }
  } finally {
    writingPlayer = false;
  }
}

